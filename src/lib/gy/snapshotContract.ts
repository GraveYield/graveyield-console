/** The canonical WSOL mint — the one the indexer's D-01 gate validates against. */
export const CANONICAL_WSOL_MINT = WSOL_MINT;

export type PendingCriterion = "pending";

export interface SnapshotCriteria {
  c1Inactivity: "pass" | "fail" | "pending";
  c3MinTvl: "pass" | "fail" | "pending";
  c2PriceCollapse: PendingCriterion;
  c4LpBurned: PendingCriterion;
  c5LpLocked: PendingCriterion;
  c6MultiEpoch: PendingCriterion;
}

export interface SnapshotLastSwap {
  unixTs: number;
  slot: number;
  signature: string;
}

/**
 * The machine-checkable M1 sourcing acceptance (GY-M1-ODR-001 §3), carried
 * verbatim in every emitted pool. The console validates it as exactly as
 * the producer asserts it — a pool that did not pass the D-01 gate can
 * never appear in the pool list.
 */
export interface SnapshotM1Sourcing {
  eligible: true;
  wsolSide: "pc_mint";
  reason: null;
}

export interface SnapshotPool {
  address: string;
  ammProgramId: string;
  /** Raydium AmmInfo coin_mint — the base-side mint; non-WSOL for every emitted pool. */
  coinMint: string;
  /** Raydium AmmInfo pc_mint — the quote-side mint; the canonical WSOL mint for every emitted pool. */
  pcMint: string;
  baseMint: string;
  /** Always the canonical WSOL mint here — D-01 emits only pc_mint-WSOL pools. */
  quoteMint: string;
  lpMint: string;
  wsolSide: { memecoinMint: string; coinIsWsol: boolean };
  m1Sourcing: SnapshotM1Sourcing;
  /** u64 exact decimal strings — never numbers. */
  wsolReserveLamports: string;
  memecoinReserveRaw: string;
  memecoinDecimals: number;
  lpSupplyRaw: string;
  lastSwap: SnapshotLastSwap | null;
  criteria: SnapshotCriteria;
  fingerprint: string;
  fetchedAtUnixMs: number;
}

export interface ConsoleSnapshot {
  schemaVersion: 2;
  generatedAtUnixMs: number;
  cluster: string;
  indexerGitHead: string | null;
  provenance: {
    source: string;
    endpointKind: string;
    slotLowerBound: number;
    slotUpperBound: number;
    ordering: string;
    fingerprintPolicy: string;
  };
  freshness: { maxAgeMs: number };
  counts: {
    rawAccounts: number;
    parsedPools: number;
    supportedWsolPairs: number;
    m1SourcingRejected: number;
    enriched: number;
  };
  failures: { stage: string; pool?: string; reason: string }[];
  thresholds: { inactivitySeconds: string; minTvlLamports: string };
  pools: SnapshotPool[];
}

export class SnapshotError extends Error {
  constructor(message: string) {
    super(`snapshot: ${message}`);
    this.name = "SnapshotError";
  }
}

/** The exhaustive top-level key set (mirrors the indexer's CONSOLE_SNAPSHOT_KEYS). */
const SNAPSHOT_ROOT_KEYS = [
  "schemaVersion",
  "generatedAtUnixMs",
  "cluster",
  "indexerGitHead",
  "provenance",
  "freshness",
  "counts",
  "failures",
  "thresholds",
  "pools",
] as const;

/** The exhaustive per-pool key set (mirrors the indexer's SNAPSHOT_POOL_KEYS). */
const SNAPSHOT_POOL_KEYS = [
  "address",
  "ammProgramId",
  "coinMint",
  "pcMint",
  "baseMint",
  "quoteMint",
  "lpMint",
  "wsolSide",
  "m1Sourcing",
  "wsolReserveLamports",
  "memecoinReserveRaw",
  "memecoinDecimals",
  "lpSupplyRaw",
  "lastSwap",
  "criteria",
  "fingerprint",
  "fetchedAtUnixMs",
] as const;

const U64_RE = /^[0-9]+$/;
const U64_MAX = "18446744073709551615";
const PUBKEY_RE = /^[1-9A-HJ-NP-Za-km-z]{32,44}$/;

function isObj(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

/** Unknown AND missing keys are rejected — the contract key set is exhaustive. */
function exactKeys(v: Record<string, unknown>, expected: readonly string[], what: string): void {
  const got = Object.keys(v).sort();
  const want = [...expected].sort();
  const missing = want.filter((k) => !got.includes(k));
  const unknown = got.filter((k) => !want.includes(k));
  const parts: string[] = [];
  if (missing.length > 0) parts.push(`missing ${missing.join(", ")}`);
  if (unknown.length > 0) parts.push(`unknown ${unknown.join(", ")}`);
  if (parts.length > 0) throw new SnapshotError(`${what} keys must be exactly the contract set (${parts.join("; ")})`);
}

/** Subset check for records with an optional key (e.g. failures[].pool). */
function noUnknownKeys(v: Record<string, unknown>, allowed: readonly string[], what: string): void {
  const unknown = Object.keys(v).filter((k) => !allowed.includes(k));
  if (unknown.length > 0) throw new SnapshotError(`${what} has unknown keys: ${unknown.join(", ")}`);
}

function str(v: unknown, what: string): string {
  if (typeof v !== "string" || v.length === 0) throw new SnapshotError(`${what} must be a non-empty string`);
  return v;
}

function num(v: unknown, what: string): number {
  if (typeof v !== "number" || !Number.isFinite(v)) throw new SnapshotError(`${what} must be a finite number`);
  return v;
}

function int(v: unknown, what: string): number {
  const n = num(v, what);
  if (!Number.isInteger(n) || n < 0) throw new SnapshotError(`${what} must be a non-negative integer`);
  return n;
}

function bool(v: unknown, what: string): boolean {
  if (typeof v !== "boolean") throw new SnapshotError(`${what} must be boolean`);
  return v;
}

function u64str(v: unknown, what: string): string {
  if (typeof v !== "string" || !U64_RE.test(v) || (v.length > 1 && v[0] === "0")) {
    throw new SnapshotError(`${what} must be an exact u64 decimal string, got ${JSON.stringify(v)}`);
  }
  // Numeric range check: compare by length first, then lexicographically.
  if (v.length > U64_MAX.length || (v.length === U64_MAX.length && v > U64_MAX)) {
    throw new SnapshotError(`${what} exceeds u64 range`);
  }
  return v;
}

function pubkey(v: unknown, what: string): string {
  const s = str(v, what);
  if (!PUBKEY_RE.test(s)) throw new SnapshotError(`${what} is not a base58 pubkey`);
  return s;
}

function criterionState(v: unknown, what: string): "pass" | "fail" | "pending" {
  if (v !== "pass" && v !== "fail" && v !== "pending") {
    throw new SnapshotError(`${what} must be pass|fail|pending`);
  }
  return v;
}

function pendingOnly(v: unknown, what: string): PendingCriterion {
  if (v !== "pending") throw new SnapshotError(`${what} must be "pending" (not derivable upstream)`);
  return "pending";
}

/**
 * Parse and fully validate an untyped snapshot payload against the
 * ConsoleSnapshotV2 contract (mirroring the indexer's normative reader,
 * src/consoleSnapshotParse.ts). Throws SnapshotError on any violation.
 */
export function parseSnapshot(raw: unknown): ConsoleSnapshot {
  if (!isObj(raw)) throw new SnapshotError("root must be an object");
  exactKeys(raw, SNAPSHOT_ROOT_KEYS, "root");

  // ---- Explicit schema version: only v2, v1 deliberately unsupported.
  if (raw.schemaVersion === 1) {
    throw new SnapshotError(
      "schemaVersion 1 is not supported by this console and is never reinterpreted as v2 — v1 lacks the D-01 sourcing fields (coinMint/pcMint/m1Sourcing, counts.m1SourcingRejected). Regenerate the artifact with a schema-v2 grave-indexer (`grave-indexer console-snapshot`, PR #4) — see src/lib/gy/snapshot-fixture/PROVENANCE.md.",
    );
  }
  if (raw.schemaVersion !== 2) {
    throw new SnapshotError(
      `unsupported schemaVersion: got ${JSON.stringify(raw.schemaVersion)}, this console accepts only schemaVersion 2`,
    );
  }

  const generatedAtUnixMs = num(raw.generatedAtUnixMs, "generatedAtUnixMs");
  if (generatedAtUnixMs <= 0) throw new SnapshotError("generatedAtUnixMs must be positive");
  const cluster = str(raw.cluster, "cluster");
  if (cluster !== "devnet" && cluster !== "mainnet-beta") {
    throw new SnapshotError(`cluster must be "devnet" | "mainnet-beta", got ${JSON.stringify(cluster)}`);
  }
  const indexerGitHead = raw.indexerGitHead === null ? null : str(raw.indexerGitHead, "indexerGitHead");

  // ---- Provenance (bracketed slots, pinned source/ordering).
  if (!isObj(raw.provenance)) throw new SnapshotError("provenance must be an object");
  exactKeys(raw.provenance, ["source", "endpointKind", "slotLowerBound", "slotUpperBound", "ordering", "fingerprintPolicy"], "provenance");
  const prov = raw.provenance;
  const provenance = {
    source: str(prov.source, "provenance.source"),
    endpointKind: str(prov.endpointKind, "provenance.endpointKind"),
    slotLowerBound: num(prov.slotLowerBound, "provenance.slotLowerBound"),
    slotUpperBound: num(prov.slotUpperBound, "provenance.slotUpperBound"),
    ordering: str(prov.ordering, "provenance.ordering"),
    fingerprintPolicy: str(prov.fingerprintPolicy, "provenance.fingerprintPolicy"),
  };
  if (provenance.source !== "raydium-v4-gpa") {
    throw new SnapshotError(`provenance.source must be "raydium-v4-gpa", got ${JSON.stringify(provenance.source)}`);
  }
  if (provenance.endpointKind !== "public-rpc" && provenance.endpointKind !== "private-rpc") {
    throw new SnapshotError(
      `provenance.endpointKind must be "public-rpc" | "private-rpc", got ${JSON.stringify(provenance.endpointKind)}`,
    );
  }
  if (provenance.ordering !== "ascending base58 pool address (reproducible)") {
    throw new SnapshotError(
      `provenance.ordering must be "ascending base58 pool address (reproducible)", got ${JSON.stringify(provenance.ordering)}`,
    );
  }
  if (provenance.slotLowerBound > provenance.slotUpperBound) {
    throw new SnapshotError("provenance slot bounds inverted");
  }

  // ---- Freshness.
  if (!isObj(raw.freshness)) throw new SnapshotError("freshness must be an object");
  exactKeys(raw.freshness, ["maxAgeMs"], "freshness");
  const maxAgeMs = num(raw.freshness.maxAgeMs, "freshness.maxAgeMs");
  if (maxAgeMs <= 0) throw new SnapshotError("freshness.maxAgeMs must be positive");

  // ---- Counts (incl. the v2 m1SourcingRejected total).
  if (!isObj(raw.counts)) throw new SnapshotError("counts must be an object");
  exactKeys(raw.counts, ["rawAccounts", "parsedPools", "supportedWsolPairs", "m1SourcingRejected", "enriched"], "counts");
  const counts = {
    rawAccounts: int(raw.counts.rawAccounts, "counts.rawAccounts"),
    parsedPools: int(raw.counts.parsedPools, "counts.parsedPools"),
    supportedWsolPairs: int(raw.counts.supportedWsolPairs, "counts.supportedWsolPairs"),
    m1SourcingRejected: int(raw.counts.m1SourcingRejected, "counts.m1SourcingRejected"),
    enriched: int(raw.counts.enriched, "counts.enriched"),
  };
  // Rejections cannot exceed the WSOL-supported corpus they came from.
  if (counts.m1SourcingRejected > counts.supportedWsolPairs) {
    throw new SnapshotError(
      `counts.m1SourcingRejected (${counts.m1SourcingRejected}) exceeds counts.supportedWsolPairs (${counts.supportedWsolPairs})`,
    );
  }

  // ---- Failures (every m1-sourcing rejection must appear exactly once).
  if (!Array.isArray(raw.failures)) throw new SnapshotError("failures must be an array");
  const failures = raw.failures.map((f, i) => {
    if (!isObj(f)) throw new SnapshotError(`failures[${i}] must be an object`);
    // `pool` is the one optional contract key; stage/reason are required.
    noUnknownKeys(f, ["stage", "pool", "reason"], `failures[${i}]`);
    const stage = str(f.stage, `failures[${i}].stage`);
    const pool = f.pool === undefined ? undefined : str(f.pool, `failures[${i}].pool`);
    const reason = str(f.reason, `failures[${i}].reason`);
    return pool === undefined ? { stage, reason } : { stage, pool, reason };
  });
  const sourcingFailures = failures.filter((f) => f.stage === "m1-sourcing");
  if (sourcingFailures.length !== counts.m1SourcingRejected) {
    throw new SnapshotError(
      `counts.m1SourcingRejected (${counts.m1SourcingRejected}) != failures with stage "m1-sourcing" (${sourcingFailures.length}) — rejected pools must each appear exactly once in failures`,
    );
  }
  const sourcingFailurePools = new Set<string>();
  for (const f of sourcingFailures) {
    if (f.pool === undefined) throw new SnapshotError(`a stage "m1-sourcing" failure is missing its pool address`);
    if (sourcingFailurePools.has(f.pool)) {
      throw new SnapshotError(`pool ${f.pool} appears more than once under stage "m1-sourcing"`);
    }
    sourcingFailurePools.add(f.pool);
  }

  // ---- Thresholds (exact u64 decimal strings).
  if (!isObj(raw.thresholds)) throw new SnapshotError("thresholds must be an object");
  exactKeys(raw.thresholds, ["inactivitySeconds", "minTvlLamports"], "thresholds");
  const thresholds = {
    inactivitySeconds: u64str(raw.thresholds.inactivitySeconds, "thresholds.inactivitySeconds"),
    minTvlLamports: u64str(raw.thresholds.minTvlLamports, "thresholds.minTvlLamports"),
  };

  // ---- Pools (exhaustive keys, exact D-01 sourcing metadata).
  if (!Array.isArray(raw.pools)) throw new SnapshotError("pools must be an array");
  const pools = raw.pools.map((p, i): SnapshotPool => {
    if (!isObj(p)) throw new SnapshotError(`pools[${i}] must be an object`);
    exactKeys(p, SNAPSHOT_POOL_KEYS, `pools[${i}]`);
    const at = (w: string) => `pools[${i}].${w}`;

    const address = pubkey(p.address, at("address"));
    const ammProgramId = pubkey(p.ammProgramId, at("ammProgramId"));

    // D-01 sourcing fields — validated EXACTLY, never reinterpreted:
    // coinMint non-WSOL, pcMint the canonical WSOL mint, aliases agree.
    const coinMint = pubkey(p.coinMint, at("coinMint"));
    const pcMint = pubkey(p.pcMint, at("pcMint"));
    const baseMint = pubkey(p.baseMint, at("baseMint"));
    const quoteMint = pubkey(p.quoteMint, at("quoteMint"));
    const lpMint = pubkey(p.lpMint, at("lpMint"));
    if (coinMint === CANONICAL_WSOL_MINT) {
      throw new SnapshotError(
        `${at("coinMint")} must be non-WSOL — the D-01 M1 sourcing gate only emits WSOL-on-pc_mint pools (got WSOL on coin_mint for ${address})`,
      );
    }
    if (pcMint !== CANONICAL_WSOL_MINT) {
      throw new SnapshotError(
        `${at("pcMint")} must be the canonical WSOL mint (${CANONICAL_WSOL_MINT}) — got ${JSON.stringify(pcMint)} for ${address}`,
      );
    }
    if (baseMint !== coinMint) throw new SnapshotError(`${at("baseMint")} must equal coinMint (the builder's documented aliasing)`);
    if (quoteMint !== pcMint) throw new SnapshotError(`${at("quoteMint")} must equal pcMint (the builder's documented aliasing)`);

    // The machine-checkable M1 acceptance, exactly as produced.
    if (!isObj(p.m1Sourcing)) throw new SnapshotError(`${at("m1Sourcing")} must be an object`);
    exactKeys(p.m1Sourcing, ["eligible", "wsolSide", "reason"], at("m1Sourcing"));
    if (p.m1Sourcing.eligible !== true) {
      throw new SnapshotError(`${at("m1Sourcing.eligible")} must be true for every emitted pool — a pool that did not pass the D-01 gate can never be in the pool list`);
    }
    if (p.m1Sourcing.wsolSide !== "pc_mint") {
      throw new SnapshotError(`${at("m1Sourcing.wsolSide")} must be "pc_mint", got ${JSON.stringify(p.m1Sourcing.wsolSide)}`);
    }
    if (p.m1Sourcing.reason !== null) {
      throw new SnapshotError(`${at("m1Sourcing.reason")} must be null for an emitted (accepted) pool`);
    }

    // wsolSide must agree with the validated orientation.
    if (!isObj(p.wsolSide)) throw new SnapshotError(`${at("wsolSide")} must be an object`);
    exactKeys(p.wsolSide, ["memecoinMint", "coinIsWsol"], at("wsolSide"));
    const wsolSide = {
      memecoinMint: pubkey(p.wsolSide.memecoinMint, at("wsolSide.memecoinMint")),
      coinIsWsol: bool(p.wsolSide.coinIsWsol, at("wsolSide.coinIsWsol")),
    };
    if (wsolSide.coinIsWsol !== false) {
      throw new SnapshotError(`${at("wsolSide.coinIsWsol")} must be false — the emitted orientation is pc_mint-WSOL (coin_mint non-WSOL)`);
    }
    if (wsolSide.memecoinMint !== coinMint) {
      throw new SnapshotError(`${at("wsolSide.memecoinMint")} must equal coinMint for a pc_mint-WSOL pool`);
    }

    // Exact u64 reserves/supply, decimals, last swap.
    const wsolReserveLamports = u64str(p.wsolReserveLamports, at("wsolReserveLamports"));
    const memecoinReserveRaw = u64str(p.memecoinReserveRaw, at("memecoinReserveRaw"));
    const memecoinDecimals = num(p.memecoinDecimals, at("memecoinDecimals"));
    if (!Number.isInteger(memecoinDecimals) || memecoinDecimals < 0 || memecoinDecimals > 255) {
      throw new SnapshotError(`${at("memecoinDecimals")} must be an integer in [0, 255]`);
    }
    const lpSupplyRaw = u64str(p.lpSupplyRaw, at("lpSupplyRaw"));
    let lastSwap: SnapshotLastSwap | null = null;
    if (p.lastSwap !== null) {
      if (!isObj(p.lastSwap)) throw new SnapshotError(`${at("lastSwap")} must be null or an object`);
      exactKeys(p.lastSwap, ["unixTs", "slot", "signature"], at("lastSwap"));
      const unixTs = num(p.lastSwap.unixTs, at("lastSwap.unixTs"));
      const slot = num(p.lastSwap.slot, at("lastSwap.slot"));
      const signature = str(p.lastSwap.signature, at("lastSwap.signature"));
      if (unixTs <= 0 || slot <= 0) throw new SnapshotError(`${at("lastSwap")} timestamps must be positive`);
      lastSwap = { unixTs, slot, signature };
    }
    if (!isObj(p.criteria)) throw new SnapshotError(`${at("criteria")} must be an object`);
    exactKeys(p.criteria, ["c1Inactivity", "c3MinTvl", "c2PriceCollapse", "c4LpBurned", "c5LpLocked", "c6MultiEpoch"], at("criteria"));
    const criteria: SnapshotCriteria = {
      c1Inactivity: criterionState(p.criteria.c1Inactivity, at("criteria.c1Inactivity")),
      c3MinTvl: criterionState(p.criteria.c3MinTvl, at("criteria.c3MinTvl")),
      // C2/C4/C5/C6 are not derivable upstream — a future index cannot
      // quietly invent evaluations (the indexer's reader pins the same).
      c2PriceCollapse: pendingOnly(p.criteria.c2PriceCollapse, at("criteria.c2PriceCollapse")),
      c4LpBurned: pendingOnly(p.criteria.c4LpBurned, at("criteria.c4LpBurned")),
      c5LpLocked: pendingOnly(p.criteria.c5LpLocked, at("criteria.c5LpLocked")),
      c6MultiEpoch: pendingOnly(p.criteria.c6MultiEpoch, at("criteria.c6MultiEpoch")),
    };
    const fingerprint = str(p.fingerprint, at("fingerprint"));
    const fetchedAtUnixMs = num(p.fetchedAtUnixMs, at("fetchedAtUnixMs"));
    if (fetchedAtUnixMs <= 0) throw new SnapshotError(`${at("fetchedAtUnixMs")} must be positive`);

    return {
      address,
      ammProgramId,
      coinMint,
      pcMint,
      baseMint,
      quoteMint,
      lpMint,
      wsolSide,
      m1Sourcing: { eligible: true, wsolSide: "pc_mint", reason: null },
      wsolReserveLamports,
      memecoinReserveRaw,
      memecoinDecimals,
      lpSupplyRaw,
      lastSwap,
      criteria,
      fingerprint,
      fetchedAtUnixMs,
    };
  });

  // ---- Counts consistency with the emitted pool list.
  if (counts.enriched !== pools.length) {
    throw new SnapshotError(`counts.enriched (${counts.enriched}) != pools.length (${pools.length})`);
  }
  if (pools.length > counts.supportedWsolPairs - counts.m1SourcingRejected) {
    throw new SnapshotError(
      `pools.length (${pools.length}) exceeds supportedWsolPairs - m1SourcingRejected (${counts.supportedWsolPairs - counts.m1SourcingRejected}) — enrichment can shrink the list, never grow it`,
    );
  }

  return {
    schemaVersion: 2,
    generatedAtUnixMs,
    cluster,
    indexerGitHead,
    provenance,
    freshness: { maxAgeMs },
    counts,
    failures,
    thresholds,
    pools,
  };
}

/** "fresh" within the artifact's own freshness budget, "stale" past it. */
export function snapshotFreshness(snap: ConsoleSnapshot, nowMs: number): "fresh" | "stale" {
  return nowMs - snap.generatedAtUnixMs <= snap.freshness.maxAgeMs ? "fresh" : "stale";
}

/** Artifact-level data state for badges: real within budget, stale past it. */
export function snapshotDataState(snap: ConsoleSnapshot, nowMs: number): DataState {
  return snapshotFreshness(snap, nowMs) === "fresh" ? "real" : "stale";
}

/**
 * Clock-skew tolerance for artifact timestamps. A generatedAt further in the
 * future than this is rejected by the transport (see snapshotSource.ts) — a
 * future-dated artifact would otherwise classify as fresh forever.
 */
export const SNAPSHOT_CLOCK_SKEW_TOLERANCE_MS = 5 * 60_000;

/**
 * Map a snapshot pool onto the console's UI Pool type. Snapshotted pools are
 * truthfully in the "discovered" state; score is NOT fabricated (0) —
 * snapshot-mode views must sort by real quantities (TVL, last activity).
 * C2/C4/C5/C6 ride along as pending via `snapshotCriteria`.
 */
export function poolFromSnapshot(p: SnapshotPool, snap: ConsoleSnapshot): Pool {
  const lpSupplyBig = BigInt(p.lpSupplyRaw);
  if (lpSupplyBig > BigInt(Number.MAX_SAFE_INTEGER)) {
    throw new SnapshotError(`pool ${p.address}: lpSupplyRaw exceeds JS safe-integer range`);
  }
  const note = p.lastSwap
    ? undefined
    : "Last activity not derivable in this snapshot run — shown as unavailable, not zero.";
  return {
    address: p.address,
    // Truthful labels: the quote side is WSOL by the D-01 contract (the
    // parser rejected anything else); the base side is identified by its
    // mint (symbols would require an off-chain registry — none is trusted
    // here).
    baseSymbol: `mint:${shortAddr(p.baseMint, 4, 4)}`,
    quoteSymbol: "WSOL",
    amm: "Raydium V4",
    quoteReserveLamports: BigInt(p.wsolReserveLamports),
    baseReserve: BigInt(p.memecoinReserveRaw),
    baseDecimals: p.memecoinDecimals,
    lpSupply: Number(lpSupplyBig),
    lastSwapUnix: p.lastSwap?.unixTs ?? 0,
    collapseBps: 0, // pending upstream — never rendered as a real value
    lpBurned: false, // placeholder for estimator math; REAL state is snapshotCriteria.c4LpBurned ("pending")
    lpLocked: false, // placeholder for estimator math; REAL state is snapshotCriteria.c5LpLocked ("pending")
    state: "discovered",
    score: 0, // not fabricated — snapshot views sort by real quantities
    anchorEpoch: null,
    certExpiresAt: null,
    note,
    dataSource: snapshotDataState(snap, Date.now()),
    snapshotCriteria: { c1Inactivity: p.criteria.c1Inactivity, c3MinTvl: p.criteria.c3MinTvl },
    snapshotFingerprint: p.fingerprint,
    snapshotMeta: {
      generatedAtUnixMs: snap.generatedAtUnixMs,
      maxAgeMs: snap.freshness.maxAgeMs,
      fetchedAtUnixMs: p.fetchedAtUnixMs,
    },
    snapshotReserves: {
      wsolReserveLamports: p.wsolReserveLamports,
      memecoinReserveRaw: p.memecoinReserveRaw,
      lpSupplyRaw: p.lpSupplyRaw,
      lastSwap: p.lastSwap,
    },
  };
}

/** All snapshot pools mapped to UI pools, in the artifact's canonical order. */
export function snapshotPools(snap: ConsoleSnapshot): Pool[] {
  return snap.pools.map((p) => poolFromSnapshot(p, snap));
}

/**
 * Six-criteria rows for snapshot pools. Mirrors estimator.criteriaOf()'s
 * shape and thresholds, but the states come from the snapshot's honest
 * evaluation: C1/C3 as derived upstream, C2/C4/C5/C6 always "pending".
 */
export function snapshotCriteriaOf(pool: Pool, now: number, snap: ConsoleSnapshot): Criterion[] {
  const sc = pool.snapshotCriteria;
  if (!sc) throw new SnapshotError("snapshotCriteriaOf requires a snapshot-backed pool");
  const inactivityDays = Number(BigInt(snap.thresholds.inactivitySeconds) / 86_400n);
  const minTvlSol = Number(BigInt(snap.thresholds.minTvlLamports)) / 1e9;
  const daysSinceSwap =
    pool.lastSwapUnix > 0 ? Math.floor((now - pool.lastSwapUnix * 1000) / 86_400_000) : null;
  return [
    {
      id: "C1",
      name: "Trading inactivity",
      detail:
        "≥ 90 days since last swap. Evidence: indexer-derived from Raydium V4 history in the snapshot — the oracle-signed attestation is a later pipeline step.",
      threshold: `≥ ${inactivityDays} days`,
      state: sc.c1Inactivity,
      value: daysSinceSwap === null ? "unavailable" : `${daysSinceSwap} days`,
    },
    {
      id: "C2",
      name: "Price collapse from launch",
      detail:
        "Requires the oracle-attested launch price (init-once LaunchPrice PDA). Not derivable from this snapshot — pending, never estimated.",
      threshold: "≥ 9,900 bps",
      state: "pending",
      value: "not attested",
    },
    {
      id: "C3",
      name: "Minimum residual TVL",
      detail:
        "Quote-side (WSOL) vault balance must still clear the floor. Snapshot value read live from the pool's vault token account.",
      threshold: `≥ ${minTvlSol} SOL`,
      state: sc.c3MinTvl,
      value: `${Number(pool.quoteReserveLamports) / 1e9} SOL`,
    },
    {
      id: "C4",
      name: "LP supply not burned",
      detail:
        "Requires the original-supply baseline / burn-dust comparison. Snapshot carries the raw LP supply only — pending, never guessed.",
      threshold: "supply > dust threshold",
      state: "pending",
      value: `${pool.lpSupply.toLocaleString()} LP (raw)`,
    },
    {
      id: "C5",
      name: "No locked LP",
      detail:
        "Requires locker introspection (UNCX marker PDA) — LOCKER-002 keeps off-chain locker evidence out of the snapshot. Pending.",
      threshold: "no locks",
      state: "pending",
      value: "not introspected",
    },
    {
      id: "C6",
      name: "Multi-epoch confirmation",
      detail:
        "Requires an on-chain EligibilityAnchor epoch gap (Phase 1 → Phase 2). No anchor exists for a discovered pool — pending.",
      threshold: "≥ 2 epochs",
      state: "pending",
      value: "no anchor",
    },
  ];
}
