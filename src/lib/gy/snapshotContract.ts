// Console snapshot CONTRACT — artifact-free, isomorphic (P4.1 Step 1).
//
// Everything in this module is pure: it validates and maps ConsoleSnapshotV2
// payloads without reading files, fetching URLs, or importing the committed
// artifact. That makes it safe to import from client code (the Graveyard
// re-validates every transport payload with the exact same fail-closed gate
// the server used) and from server-side transport code alike.
//
// The build-time committed artifact binding lives in snapshot.ts, which
// re-exports this module. Import from there only when you actually want the
// committed snapshot.json pulled into your bundle.
//
// Contract rules (schema v2, D-01 M1-sourcing extension):
//   - FAIL-CLOSED: any missing/invalid required field throws SnapshotError.
//     A broken artifact can never silently render as data.
//   - EXPLICIT SCHEMA VERSION: only schemaVersion 2 is accepted. A v1
//     artifact is REJECTED with an actionable error — it is never silently
//     reinterpreted as v2 (v1 lacks coinMint/pcMint/m1Sourcing and
//     counts.m1SourcingRejected, so reinterpretation would be unsound).
//     Unsupported future/missing versions are rejected for the same reason.
//     This is a deliberate, tested v1 policy (strict v2-only — Option A):
//     there is no dual validator, no v1 backfill, and a v1 payload can
//     never enter a sourcing-verified flow. Regenerate v1 artifacts with a
//     schema-v2 indexer instead.
//   - EXHAUSTIVE FIELDS: unknown AND missing keys are rejected at every
//     level (root/provenance/freshness/counts/failures[]/thresholds/
//     pools[]/m1Sourcing/wsolSide/lastSwap/criteria) — nothing is silently
//     ignored, and a future producer cannot smuggle fields past this gate.
//   - Data states are explicit and honest end to end:
//       real        — from the snapshot, within its freshness budget
//       stale       — from the snapshot, past the freshness budget
//       unavailable — the indexer recorded the field as not derivable
//                     (e.g. last-swap failures) — never rendered as zero
//       simulated   — fixture data (data.ts), labelled by the shell badge
//   - D-01 SOURCING CONSISTENCY: every pool in the artifact has PASSED the
//     M1 quote-side sourcing predicate (GY-M1-ODR-001 §3). The console
//     re-validates exactly what the producer asserts and rejects anything
//     else:
//         coinMint   — non-WSOL (WSOL on coin_mint is the rejected side)
//         pcMint     — the canonical WSOL mint (one definition, shared
//                      with estimator.ts — no second WSOL constant)
//         baseMint   — must equal coinMint (documented builder aliasing)
//         quoteMint  — must equal pcMint (same aliasing)
//         m1Sourcing — exactly { eligible: true, wsolSide: "pc_mint",
//                              reason: null } for every emitted pool
//         wsolSide   — memecoinMint === coinMint, coinIsWsol === false
//     A deviation of ANY of these rejects the artifact fail-closed.
//   - COUNTS CONSISTENCY: enriched === pools.length;
//     m1SourcingRejected <= supportedWsolPairs; pools.length <=
//     supportedWsolPairs - m1SourcingRejected (enrichment failures may
//     shrink the emitted list, never grow it); every rejected pool appears
//     exactly once in `failures` under stage "m1-sourcing" with a pool
//     address — the count can never drift into a misleading total.
//   - Criteria honesty: only C1/C3 are evaluated upstream. C2/C4/C5/C6 are
//     hard-pinned "pending" by the indexer; the loader refuses any other
//     value so a future index cannot quietly invent evaluations.
//   - THE CONSOLE IS NOT AN ELIGIBILITY AUTHORITY: this contract validates
//     artifact structure and internal consistency only. GraveScanner
//     remains the on-chain authority for pool eligibility; schema validity
//     here proves nothing beyond "the artifact is well-formed, internally
//     consistent, and claims the provenance it carries". It does not add
//     holder-level or cryptographic guarantees.
//
// Shared producer/consumer contract: the normative reader is the
// indexer's src/consoleSnapshotParse.ts (GraveYield/grave-indexer, PR #4).
// This module mirrors it rule-for-rule; the committed fixture
// (src/lib/gy/snapshot.json) is generated by the REAL indexer serializer
// and digest-pinned — see src/lib/gy/snapshot-fixture/
// (PROVENANCE.md + generate-fixture.ts) for the sharing mechanism and the
// regeneration procedure. Contract tests live in __tests__/snapshot.test.ts
// (this side) and __tests__/snapshotV2Compat.test.ts (cross-repo).

